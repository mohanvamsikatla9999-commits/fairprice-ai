import type { CatalogProduct } from "./catalog-types";

function p(
  brand: string,
  model: string,
  msrpInr: number,
  aliases: string[] = [],
  variants?: CatalogProduct["variants"],
): CatalogProduct {
  const slug = `${brand}-${model}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  return {
    brand,
    model,
    slug,
    categorySlug: "mobiles",
    aliases: [`${brand} ${model}`.toLowerCase(), ...aliases.map((a) => a.toLowerCase())],
    msrpInr,
    variants,
  };
}

